-- Cập nhật TRIGIA cho khớp với chi tiết hóa đơn mới
UPDATE HOADON
SET TRIGIA = (SELECT SUM(C.SL * S.GIA)
              FROM CTHD C JOIN SANPHAM S ON C.MASP = S.MASP
              WHERE C.SOHD = HOADON.SOHD)
WHERE SOHD >= 1012;
GO

SELECT S.MASP, S.TENSP,
       SUM(CASE WHEN YEAR(H.NGHD)=2006 THEN C.SL*S.GIA ELSE 0 END) AS DT2006,
       SUM(CASE WHEN YEAR(H.NGHD)=2007 THEN C.SL*S.GIA ELSE 0 END) AS DT2007,
       SUM(C.SL*S.GIA) AS DT2006_2007
FROM SANPHAM S
JOIN CTHD C  ON S.MASP = C.MASP
JOIN HOADON H ON C.SOHD = H.SOHD
WHERE YEAR(H.NGHD) IN (2006, 2007)
GROUP BY S.MASP, S.TENSP
ORDER BY S.MASP;