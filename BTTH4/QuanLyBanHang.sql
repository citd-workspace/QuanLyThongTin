SELECT NV.MANV, NV.HOTEN, MONTH(HD.NGHD) AS THANG, SUM(HD.TRIGIA) AS DOANHTHU
FROM NHANVIEN NV JOIN HOADON HD ON NV.MANV = HD.MANV
WHERE YEAR(HD.NGHD) = 2006
GROUP BY NV.MANV, NV.HOTEN, MONTH(HD.NGHD)
ORDER BY NV.MANV, THANG;

